const { app, BrowserWindow, ipcMain } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
app.setPath('userData', fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'vessel-json-')))
app.whenReady().then(async () => {
  for (const [name,value] of Object.entries({'settings:get':{theme:'light',font:'Plus Jakarta Sans',fontSize:14,accent:'#16a34a'},'app-state:get':null,'app-state:set':null,'markdown:pending':[]})) ipcMain.handle(name,()=>value)
  const win=new BrowserWindow({show:true,width:1200,height:800,webPreferences:{preload:path.resolve('out/preload/index.js'),sandbox:false}})
  await win.loadFile(path.resolve('out/renderer/index.html'),{hash:'/devtools/json'})
  win.webContents.on('console-message', (_e,_l,message)=>console.log(message))
  const js=code=>win.webContents.executeJavaScript(code)
  await new Promise(r=>setTimeout(r,500))
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='JSON 格式化')?.click()`)
  for(let i=0;i<50;i++){if(await js(`!!document.querySelector('.monaco-editor textarea')`))break;await new Promise(r=>setTimeout(r,100))}
  assert.equal(await js(`document.querySelectorAll('.monaco-editor').length`),1)
  win.focus()
  const point = await js(`(() => {const r=document.querySelector('.view-lines').getBoundingClientRect();return {x:Math.round(r.x+20),y:Math.round(r.y+10)}})()`)
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point})
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point})
  await win.webContents.insertText('{"name":"Vessel","enabled":true}')
  await new Promise(r=>setTimeout(r,200))
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='格式化').click()`)
  await new Promise(r=>setTimeout(r,300))
  console.log(await js(`document.querySelector('.view-lines').textContent`))
  fs.writeFileSync('/tmp/vessel-json-tool.png',(await win.webContents.capturePage()).toPNG())
  assert(await js(`document.querySelector('.view-lines').textContent.includes('Vessel')`))
  assert(await js(`document.querySelectorAll('.view-lines .view-line').length>=4`))
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='压缩').click()`)
  await new Promise(r=>setTimeout(r,200))
  assert.equal(await js(`document.querySelectorAll('.view-lines .view-line').length`),1)
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='格式化').click()`)
  await new Promise(r=>setTimeout(r,200))
  fs.writeFileSync('/tmp/vessel-json-tool.png',(await win.webContents.capturePage()).toPNG())
  await js(`document.querySelector('[aria-label="清空内容"]').click()`)
  await new Promise(r=>setTimeout(r,100))
  assert(await js(`document.querySelector('[aria-label="复制内容"]').disabled`))
  console.log('PASS: single Monaco editor, input, in-place formatting/compression, clear')
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='图片 OCR').click()`)
  await new Promise(r=>setTimeout(r,300))
  assert.equal(await js(`document.querySelector('.ocr-tabs-bar').getBoundingClientRect().height`),38)
  fs.writeFileSync('/tmp/vessel-tools-ocr-design.png',(await win.webContents.capturePage()).toPNG())
  await js(`[...document.querySelectorAll('button')].find(b=>b.textContent==='颜色转换').click()`)
  await new Promise(r=>setTimeout(r,200))
  assert(await js(`!!document.querySelector('input[aria-label="RGBA"]')`))
  fs.writeFileSync('/tmp/vessel-tools-color-design.png',(await win.webContents.capturePage()).toPNG())
  console.log('PASS: compact OCR tabs and color tool')
  app.quit()
}).catch(e=>{console.error(e);app.exit(1)})
