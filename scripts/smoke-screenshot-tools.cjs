const { app, BrowserWindow, clipboard } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
app.setPath('userData', fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'vessel-shot-tools-')))
app.on('window-all-closed', () => {})
const wait = ms => new Promise(r => setTimeout(r, ms))
app.whenReady().then(async () => {
 const source = new BrowserWindow({show:false,width:900,height:600,webPreferences:{backgroundThrottling:false}})
 await source.loadURL('data:text/html,'+encodeURIComponent('<body style="margin:0;background:#fff"><div style="padding:140px 60px;font:42px Arial;color:#000">VESSEL OCR TEST 123</div></body>'))
 const image = (await source.webContents.capturePage()).toDataURL(); source.destroy()
 async function capture() {
  const win = new BrowserWindow({show:true,width:900,height:600,frame:false,webPreferences:{preload:path.resolve('out/preload/screenshot.js'),sandbox:true}})
  let result
  win.webContents.ipc.handle('shot:data',()=>({mode:'capture',image}))
  win.webContents.ipc.handle('shot:copy-text',(_e,text)=>clipboard.writeText(text))
  win.webContents.ipc.handle('shot:finish',(_e,data,pin)=>{ result={data,pin} })
  win.webContents.ipc.handle('shot:close',()=>win.close())
  await win.loadFile(path.resolve('out/renderer/screenshot.html')); await wait(500)
  const js = code=>win.webContents.executeJavaScript(code)
  win.webContents.sendInputEvent({type:'mouseMove',x:40,y:40}); await wait(100)
  assert.match(await js(`document.querySelector('.shot-color-inspector').textContent`), /#FFFFFF/)
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'C'}); await wait(100)
  assert.equal(clipboard.readText(),'#FFFFFF')
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,x:30,y:100})
  win.webContents.sendInputEvent({type:'mouseMove',modifiers:['leftButtonDown'],x:750,y:300})
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:750,y:300}); await wait(200)
  return {win,js,result:()=>result}
 }
 const shot = await capture()
 await shot.js(`document.querySelector('.shot-step').click()`)
 shot.win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,x:500,y:240})
 shot.win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,x:500,y:240}); await wait(100)
 assert(await shot.js(`document.querySelector('.shot-steps').getContext('2d').getImageData(500,240,1,1).data[3]>0`))
 await shot.js(`document.querySelector('.shot-pin').click()`); await wait(300)
 assert(shot.result()?.pin)
 const red = await shot.js(`(async()=>{const image=new Image();image.src=${JSON.stringify(shot.result().data)};await image.decode();const c=document.createElement('canvas');c.width=image.width;c.height=image.height;const ctx=c.getContext('2d');ctx.drawImage(image,0,0);const data=ctx.getImageData(0,0,c.width,c.height).data;let n=0;for(let i=0;i<data.length;i+=4)if(data[i]>180&&data[i+1]<110&&data[i+2]<110)n++;return n})()`)
 assert(red>50,'step annotation is included in exported pixels'); shot.win.destroy()
 const ocr = await capture()
 await ocr.js(`document.querySelector('.shot-recognize').click()`)
 let text=''
 for(let i=0;i<120;i++){await wait(500);text=await ocr.js(`document.querySelector('.shot-ocr textarea')?.value||''`);if(text)break}
 assert.match(text,/VESSEL/i);assert.match(text,/123/)
 await ocr.js(`document.querySelector('.shot-ocr button').click()`);await wait(100)
 assert.equal(clipboard.readText(),text)
 console.log('PASS original pixel color/copy, numbered steps/export, local screenshot OCR/copy')
 app.exit(0)
}).catch(error=>{console.error(error);app.exit(1)})
setTimeout(()=>app.exit(1),90000).unref()
