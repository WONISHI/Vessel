// Isolated desktop test. Uses a temporary profile and a loopback S3 fixture only.
const { app, BrowserWindow, ipcMain } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const profile = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'vessel-settings-smoke-'))
app.setPath('userData', profile)
const delay = ms => new Promise(r => setTimeout(r, ms))
const deadline = setTimeout(() => { console.error('Settings smoke timed out'); app.exit(1) }, 40000)
function loadTS(file) {
  const mod = new (require('node:module'))(file, module)
  mod.filename = file; mod.paths = module.paths
  mod.require = id => id.startsWith('.') ? loadTS(path.resolve(path.dirname(file), id) + '.ts') : require(id)
  mod._compile(require('typescript').transpile(fs.readFileSync(file, 'utf8'), { module: 1, target: 9 }), file)
  return mod.exports
}
app.whenReady().then(async () => {
  for (const [name, result] of Object.entries({ 'markdown:pending': [], 'workspace:readDirectory': [], 'app-state:get': null, 'app-state:set': undefined, 'browser:extensions:list': [], 'files:watch': 'watch', 'files:unwatch': undefined })) ipcMain.handle(name, () => result)
  const win = new BrowserWindow({ show: false, width: 1180, height: 900, webPreferences: { preload: path.resolve('out/preload/index.js'), sandbox: false, webviewTag: true } })
  loadTS(path.resolve('src/main/settings.ts')).registerSettings(win.webContents)
  await win.loadFile(path.resolve('out/renderer/index.html'))
  const js = code => win.webContents.executeJavaScript(code)
  const assert = async (code, message) => { if (!await js(code)) throw new Error(message); console.log('PASS', message) }
  await js(`localStorage.setItem('app_current_workspace',JSON.stringify({name:'Settings test',path:'/tmp',files:[]})); location.hash='/editor'`)
  await delay(1000)
  await js(`document.querySelector('button[aria-label="设置"]').click()`); await delay(700)
  await assert(`location.hash === '#/settings' && document.querySelector('button[aria-label="返回"]') !== null`, 'settings button navigates to page with back button')
  await js(`[...document.querySelectorAll('button')].find(b => b.textContent === '同步与备份').click()`)
  await assert(`JSON.stringify([...document.querySelector('[aria-label="更新频率"]').options].map(x => x.text)) === JSON.stringify(['5 分钟','10 分钟','30 分钟'])`, 'only requested backup intervals appear')
  await assert(`!document.body.innerText.includes('保留备份数量') && !document.body.innerText.includes('本地备份')`, 'local backup and retention options removed')
  await assert(`document.body.innerText.includes('尚未执行备份')`, 'no fabricated successful backup status')
  await delay(350)
  fs.writeFileSync('/tmp/vessel-settings-sync.png', (await win.webContents.capturePage()).toPNG())
  await js(`[...document.querySelectorAll('button')].find(b => b.textContent === '外观').click()`)
  await js(`const select=document.querySelector('[aria-label="主题模式"]'); select.value='dark'; select.dispatchEvent(new Event('change',{bubbles:true})); document.querySelector('button[aria-label="海蓝"]').click()`)
  await delay(200)
  await js(`[...document.querySelectorAll('button')].find(b => b.textContent === '保存').click()`); await delay(500)
  await assert(`document.documentElement.classList.contains('dark') && document.documentElement.style.getPropertyValue('--settings-accent') === '#2563eb'`, 'saved appearance applied')
  await win.reload(); await delay(800)
  await assert(`document.documentElement.classList.contains('dark')`, 'theme restored after reload')
  await js(`document.querySelector('button[aria-label="返回"]').click()`); await delay(500)
  await assert(`location.hash === '#/editor'`, 'back returns to source page')
  win.destroy(); app.quit()
}).catch(error => { console.error(error); app.exit(1) })
app.on('will-quit', () => { clearTimeout(deadline); fs.rmSync(profile, { recursive: true, force: true }) })
