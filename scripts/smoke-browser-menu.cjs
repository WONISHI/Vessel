const { app, BrowserWindow, ipcMain } = require('electron')
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
app.setPath('userData', fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'vessel-menu-')))
app.whenReady().then(async () => {
  const handlers = { 'settings:get': { theme:'light', font:'Plus Jakarta Sans', fontSize:14, accent:'#16a34a' }, 'browser:extensions:list': [], 'browser:extensions:close': null, 'browser:devtools': null, 'browser:devices': [], 'browser:emulate': null, 'browser:history:list': [{ id:1, title:'Test history',url:'https://example.com',visitedAt:Date.now() }], 'markdown:pending': [], 'workspace:readDirectory': [], 'app-state:get': null, 'app-state:set': null, 'files:watch':'test', 'files:unwatch':null }
  for (const [name,value] of Object.entries(handlers)) ipcMain.handle(name, () => value)
  const win = new BrowserWindow({ show:false, width:1200, height:800, webPreferences: { preload:path.resolve('out/preload/index.js'), sandbox:false, webviewTag:true } })
  await win.loadFile(path.resolve('out/renderer/index.html'), { hash:'/browser' })
  const js = code => win.webContents.executeJavaScript(code)
  await new Promise(resolve => setTimeout(resolve, 1000))
  const click = async selector => {
    const point = await js(`(() => { const r=document.querySelector(${JSON.stringify(selector)}).getBoundingClientRect(); return {x:Math.round(r.x+r.width/2), y:Math.round(r.y+r.height/2)} })()`)
    win.webContents.sendInputEvent({ type:'mouseDown',button:'left',clickCount:1,...point })
    win.webContents.sendInputEvent({ type:'mouseUp',button:'left',clickCount:1,...point })
    await new Promise(resolve => setTimeout(resolve, 250))
  }
  await click('[aria-label="浏览器更多"]')
  assert(await js(`Boolean(document.querySelector('[role="menu"]'))`))
  assert.equal(await js(`document.querySelectorAll('[role="menuitem"]').length`), 4)
  await click('[aria-label="放大"]')
  assert(await js(`document.querySelector('[role="menu"]').textContent.includes('110%')`))
  await click('[aria-label="缩小"]')
  assert(await js(`document.querySelector('[role="menu"]').textContent.includes('100%')`))
  const point = await js(`(() => { const r=document.querySelector('[aria-label="放大"]').getBoundingClientRect(); return {x:Math.round(r.x+10),y:Math.round(r.y+10)} })()`)
  win.webContents.sendInputEvent({ type:'mouseMove', ...point })
  await new Promise(resolve => setTimeout(resolve,100))
  assert.equal(await js(`getComputedStyle(document.querySelector('[aria-label="放大"]')).color`), 'rgb(255, 255, 255)')
  fs.writeFileSync('/tmp/vessel-browser-menu.png', (await win.webContents.capturePage()).toPNG())
  console.log('PASS: shadcn menu, persistent zoom controls, percentage and white hover icon')
  await js(`[...document.querySelectorAll('[role="menuitem"]')].find(item => item.textContent.includes('历史记录')).click()`)
  await new Promise(resolve => setTimeout(resolve,600))
  assert(await js(`document.querySelector('[role="dialog"]').textContent.includes('今天')`))
  assert(await js(`document.querySelector('[role="dialog"]').textContent.includes('Test history')`))
  assert.equal(await js(`document.body.style.pointerEvents`), '')
  assert.equal(await js(`document.querySelectorAll('[data-state="open"][class*="bg-black/80"]').length`),0)
  fs.writeFileSync('/tmp/vessel-history-sheet.png',(await win.webContents.capturePage()).toPNG())
  await click('[aria-label="搜索历史记录"]')
  win.webContents.insertText('no matching history')
  await new Promise(resolve => setTimeout(resolve,100))
  assert(await js(`document.querySelector('[role="dialog"]').textContent.includes('没有匹配')`))
  await click('[aria-label="关闭浏览历史"]')
  await click('[aria-label="浏览器更多"]')
  console.log('PASS: nonmodal history Sheet, grouping, search and favicon element')
  await js(`[...document.querySelectorAll('[role="menuitem"]')].find(item => item.textContent.includes('设备工具栏')).click()`)
  const server = require('node:http').createServer((_req,res) => res.end('<title>Viewport</title><meta name="viewport" content="width=device-width, initial-scale=1"><p>Viewport test</p>'))
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  win.webContents.send('browser:new-tab', `http://127.0.0.1:${server.address().port}`)
  await new Promise(resolve => setTimeout(resolve,800))
  assert.equal(await js(`document.querySelector('[aria-label="设备预览边框"]').style.width`), '390px')
  assert.equal(await js(`document.querySelector('[aria-label="设备预览边框"]').style.height`), '844px')
  await click('[aria-label="设备显示缩放"]')
  await js(`[...document.querySelectorAll('[role="menuitem"]')].find(item => item.textContent === '50%').click()`)
  assert.equal(await js(`document.querySelector('[aria-label="设备预览内容"]').style.transform`), 'scale(0.5)')
  assert.equal(await js(`document.querySelector('[aria-label="设备预览边框"]').getBoundingClientRect().width`),392)
  assert.equal(await js(`document.querySelector('[aria-label="设备预览边框"]').getBoundingClientRect().height`),846)
  fs.writeFileSync('/tmp/vessel-device-toolbar.png', (await win.webContents.capturePage()).toPNG())
  console.log('PASS: viewport border dimensions and independent preview scale')
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'ESC'})
  win.webContents.sendInputEvent({type:'keyUp',keyCode:'ESC'})
  await click('[aria-label="折叠浏览器工具栏"]')
  assert(await js(`document.querySelector('.browser-toolbar').parentElement.hidden`))
  await click('[aria-label="展开浏览器工具栏"]')
  assert(!await js(`document.querySelector('.browser-toolbar').parentElement.hidden`))
  const browserPoint = await js(`(() => { const r=document.querySelector('button[aria-label="浏览器"]').getBoundingClientRect(); return {x:Math.round(r.x+15),y:Math.round(r.y+15)} })()`)
  win.webContents.sendInputEvent({type:'mouseMove',...browserPoint})
  await new Promise(resolve => setTimeout(resolve,300))
  assert(await js(`document.querySelector('[role="menu"]').textContent.includes('已打开标签页')`))
  assert(await js(`document.querySelector('[role="menu"]').textContent.includes('127.0.0.1')`))
  assert.equal(await js(`document.querySelectorAll('[aria-label="关闭 Viewport"]').length`),1)
  fs.writeFileSync('/tmp/vessel-tab-preview.png',(await win.webContents.capturePage()).toPNG())
  await click('[aria-label="关闭 Viewport"]')
  await new Promise(resolve => setTimeout(resolve,200))
  assert.equal(await js(`document.querySelectorAll('.browser-tab').length`),1)
  console.log('PASS: toolbar collapse/restore and browser preview metadata/close; empty tabs excluded')
  win.destroy(); server.close(); app.quit()
}).catch(error => { console.error(error); app.exit(1) })
setTimeout(() => app.exit(1),20000).unref()
