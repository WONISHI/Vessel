const {app,BrowserWindow,session}=require('electron')
const fs=require('node:fs'),path=require('node:path')
app.setPath('userData',fs.mkdtempSync(path.join(require('node:os').tmpdir(),'vessel-login-check-')))
app.whenReady().then(async()=>{
 const browser=session.fromPartition('persist:vessel-browser')
 browser.webRequest.onCompleted(d=>{if(d.url.startsWith('https:'))console.log('REQUEST',new URL(d.url).origin+new URL(d.url).pathname,d.statusCode)})
 browser.webRequest.onErrorOccurred(d=>{if(d.url.startsWith('https:'))console.log('FAILED',new URL(d.url).origin+new URL(d.url).pathname,d.error)})
 const ext=await browser.extensions.loadExtension(path.resolve(process.argv[2]))
 const win=new BrowserWindow({show:false,webPreferences:{session:browser,sandbox:true,contextIsolation:true,nodeIntegration:false}})
 win.webContents.on('console-message',(_e,level,message)=>{if(level===3) console.log('PAGE ERROR',message)})
 await win.loadURL(`chrome-extension://${ext.id}/login.html?/muser/login`)
 await new Promise(r=>setTimeout(r,45000))
 console.log('RESULT',await win.webContents.executeJavaScript('({title:document.title,hasLoginForm:!!document.querySelector("#iggloginform"),text:document.body.innerText.slice(0,180)})'))
 win.destroy();app.quit()
}).catch(e=>{console.error(e);app.exit(1)})
setTimeout(()=>app.exit(1),55000).unref()
