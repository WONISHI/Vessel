import type { ClipboardFilter, ClipboardState } from "@vessel/type"
import { app, BrowserWindow, clipboard, globalShortcut, nativeImage, screen } from "electron"
import { execFile, spawn, type ChildProcess } from "node:child_process"
import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { promisify } from "node:util"
import { ClipboardHistory, clipboardTextKind, MAX_CAPTURE_BYTES, type ClipboardCapture } from "./history"
import { clipboardHelperPath } from "./native-helper"

type Options = { directory?: string; helperPath?: string; preloadPath?: string; monitor?: boolean; registerShortcut?: boolean; loadPanel?: (window: BrowserWindow) => Promise<unknown> }
let activeService: ReturnType<typeof startClipboardHistory> | undefined
export function showClipboardHistory() { void activeService?.show().catch((error) => console.error("打开剪贴板失败", error)) }

/** Separate preload and scoped IPC keep clipboard history out of remote webviews. */
export function startClipboardHistory(options: Options = {}) {
  const directory = options.directory || app.getPath("userData")
  mkdirSync(directory, { recursive: true })
  const history = new ClipboardHistory(join(directory, "clipboard-history.sqlite"))
  const helper = options.helperPath || clipboardHelperPath(__dirname, app.isPackaged)
  const preferencePath = join(directory, "clipboard-history-settings.json")
  let paused = false
  try { paused = JSON.parse(readFileSync(preferencePath, "utf8")).paused === true } catch { /* First launch. */ }
  let panel: BrowserWindow | undefined
  let loading: Promise<unknown> | undefined
  let previousWindow: BrowserWindow | null = null
  let keepOpen = false
  let timer: ReturnType<typeof setInterval> | undefined
  let watcher: ChildProcess | undefined
  let signature = ""
  let readingFiles = false
  let disposed = false
  let shortcutRegistered = false
  const shortcut = process.platform === "darwin" ? "Control+V" : "Control+Shift+V"
  const notify = () => { if (panel && !panel.isDestroyed()) panel.webContents.send("clipboard:changed") }
  const state = (filter?: ClipboardFilter): ClipboardState => ({ entries: history.list(filter), total: history.count(), paused, keepOpen, shortcut, shortcutRegistered })
  const hide = (restore = false) => {
    panel?.hide()
    if (restore && previousWindow && !previousWindow.isDestroyed() && previousWindow.isVisible()) previousWindow.focus()
  }

  const capture = (nativeFiles?: string[]) => {
    if (disposed || paused) return
    try {
      const formats = clipboard.availableFormats()
      if (formats.some((format) => /org\.nspasteboard\.(Concealed|Transient|AutoGenerated)Type/i.test(format))) return
      let files = nativeFiles?.filter((file) => typeof file === "string").slice(0, 100) || []
      const fileFormat = ["public.file-url", "CF_HDROP", "text/uri-list", "x-special/gnome-copied-files"].find((format) => formats.includes(format))
      const fileData = fileFormat ? clipboard.readBuffer(fileFormat) : undefined
      if (nativeFiles === undefined && process.platform === "darwin" && fileFormat && fileData && existsSync(helper)) {
        if (readingFiles) return
        readingFiles = true
        const finish = (paths: string[]) => {
          if (!disposed && clipboard.availableFormats().includes(fileFormat) && clipboard.readBuffer(fileFormat).equals(fileData)) capture(paths)
        }
        // Electron 39 exposes only the first file URL. Re-read the native list on
        // opening/resuming, without blocking the main event loop or using stale data.
        void promisify(execFile)(helper, ["--read-files"], { timeout: 3000, maxBuffer: 1_000_000 })
          .then(({ stdout }) => { const paths = JSON.parse(stdout); finish(Array.isArray(paths) ? paths : []) })
          .catch(() => finish([])).finally(() => { readingFiles = false })
        return
      }
      if (!files.length && fileData && fileFormat !== "CF_HDROP") {
        files = fileData.toString("utf8").split(/[\r\n\0]+/).flatMap((url) => { try { return url.startsWith("file://") ? [fileURLToPath(url)] : [] } catch { return [] } }).slice(0, 100)
      }
      const text = clipboard.readText()
      const html = formats.includes("text/html") ? clipboard.readHTML() : ""
      const rtf = formats.some((format) => /(?:rtf|rich text)/i.test(format)) ? clipboard.readRTF() : ""
      if (Buffer.byteLength(text + html + rtf) > MAX_CAPTURE_BYTES) return
      let value: ClipboardCapture
      if (files.length || (fileFormat === "CF_HDROP" && fileData?.length)) {
        value = { kind: "files", text: files.join("\n") || text || "文件", files, fileFormat, fileData }
      } else if (formats.some((format) => /image|png|tiff|bitmap|jpeg/i.test(format))) {
        const image = clipboard.readImage()
        if (image.isEmpty()) return
        const size = image.getSize()
        if (size.width * size.height > 20_000_000) return
        const png = image.toPNG()
        if (png.length > MAX_CAPTURE_BYTES) return
        const ratio = Math.min(1, 440 / size.width, 250 / size.height)
        const thumbnail = "data:image/jpeg;base64," + image.resize({ width: Math.max(1, Math.round(size.width * ratio)), height: Math.max(1, Math.round(size.height * ratio)) }).toJPEG(70).toString("base64")
        value = { kind: "image", text, html, rtf, image: png, thumbnail }
      } else {
        if (!text) return
        value = { kind: clipboardTextKind(text), text, html, rtf }
      }
      const hash = createHash("sha256").update(JSON.stringify([value.kind, value.text, value.html, value.rtf, value.files, value.fileFormat]))
      if (value.image) hash.update(value.image)
      if (value.fileData) hash.update(value.fileData)
      const next = hash.digest("hex")
      if (signature === next) return
      signature = next
      if (history.add(value)) notify()
    } catch (error) { console.warn("读取剪贴板历史失败", error instanceof Error ? error.message : "未知错误") }
  }

  const copy = async (id: number, plainText = false) => {
    const entry = history.get(id)
    if (!entry) throw new Error("这条记录已不存在")
    if (plainText) {
      if (!entry.text) throw new Error("这条记录没有文本内容")
      clipboard.writeText(entry.text)
    } else if (entry.kind === "files") {
      if (process.platform === "darwin" && existsSync(helper) && entry.files?.length) {
        await promisify(execFile)(helper, ["--write-files", ...entry.files], { timeout: 5000 })
      } else if (entry.fileFormat && entry.fileData) {
        clipboard.clear()
        clipboard.writeBuffer(entry.fileFormat, entry.fileData)
      } else throw new Error("无法还原这条文件记录")
    } else {
      clipboard.write({ text: entry.text, ...(entry.html ? { html: entry.html } : {}), ...(entry.rtf ? { rtf: entry.rtf } : {}), ...(entry.image ? { image: nativeImage.createFromBuffer(entry.image) } : {}) })
    }
    capture(entry.kind === "files" && !plainText ? entry.files : undefined)
    if (!keepOpen) hide(true)
  }

  const createPanel = () => {
    const window = new BrowserWindow({
      width: 1100, height: 380, show: false, frame: false, transparent: true,
      backgroundColor: "#00000000", resizable: false, minimizable: false, maximizable: false,
      fullscreenable: false, skipTaskbar: true, alwaysOnTop: true, hasShadow: true,
      ...(process.platform === "darwin" ? { type: "panel", vibrancy: "under-window", visualEffectState: "active" } as const : {}),
      ...(process.platform === "win32" ? { backgroundMaterial: "acrylic" } as const : {}),
      webPreferences: { preload: options.preloadPath || join(__dirname, "../preload/clipboard.js"), sandbox: true, contextIsolation: true, nodeIntegration: false }
    })
    panel = window
    if (process.platform === "darwin") window.setVisibleOnAllWorkspaces(true, { visibleOnFullScreen: true, skipTransformProcessType: true })
    window.on("blur", () => { if (!keepOpen) hide() })
    window.on("close", (event) => { if (!disposed) { event.preventDefault(); hide() } })
    window.on("closed", () => { panel = undefined; loading = undefined })
    window.webContents.setWindowOpenHandler(() => ({ action: "deny" }))
    window.webContents.on("will-navigate", (event) => event.preventDefault())
    window.webContents.ipc.handle("clipboard:state", (_event, filter?: ClipboardFilter) => state(filter && typeof filter === "object" ? filter : undefined))
    window.webContents.ipc.handle("clipboard:copy", (_event, id: number, plainText: boolean) => copy(id, plainText === true))
    window.webContents.ipc.handle("clipboard:pin", (_event, id: number) => { history.pin(id); notify() })
    window.webContents.ipc.handle("clipboard:remove", (_event, id: number) => { history.remove(id); notify() })
    window.webContents.ipc.handle("clipboard:clear", () => { history.clear(); notify() })
    window.webContents.ipc.handle("clipboard:pause", (_event, value: boolean) => {
      paused = value === true
      writeFileSync(preferencePath, JSON.stringify({ paused }), { mode: 0o600 })
      if (!paused) capture()
      notify()
    })
    window.webContents.ipc.handle("clipboard:keep-open", (_event, value: boolean) => { keepOpen = value === true; notify() })
    window.webContents.ipc.handle("clipboard:close", () => hide(true))
    const rendererURL = process.env.ELECTRON_RENDERER_URL
    loading = options.loadPanel ? options.loadPanel(window) : rendererURL ? window.loadURL(new URL("clipboard.html", rendererURL).href) : window.loadFile(join(__dirname, "../renderer/clipboard.html"))
    return window
  }
  const show = async () => {
    if (disposed) return
    if (panel?.isVisible()) { hide(true); return }
    previousWindow = BrowserWindow.getFocusedWindow()
    capture()
    const window = panel && !panel.isDestroyed() ? panel : createPanel()
    const { workArea } = screen.getDisplayNearestPoint(screen.getCursorScreenPoint())
    const width = Math.max(320, workArea.width - 24), height = Math.min(380, workArea.height - 24)
    window.setBounds({ x: workArea.x + 12, y: workArea.y + workArea.height - height - 12, width, height })
    await loading
    if (disposed || window.isDestroyed()) return
    window.show()
    window.focus()
    window.webContents.send("clipboard:show")
  }
  const register = () => {
    if (disposed || options.registerShortcut === false || shortcutRegistered) return
    shortcutRegistered = globalShortcut.register(shortcut, () => void show().catch((error) => console.error("打开剪贴板失败", error)))
    if (!shortcutRegistered) console.warn(`剪贴板快捷键无法注册：${shortcut}`)
  }
  const fallback = () => {
    if (disposed || timer) return
    capture()
    timer = setInterval(() => capture(), 1000)
    timer.unref()
  }
  const onWindowCreated = (_event: Electron.Event, window: BrowserWindow) => {
    window.on("closed", () => queueMicrotask(() => {
      // The hidden utility panel must not keep Vessel alive after its last user window closes.
      if (!disposed && panel && !panel.isDestroyed() && BrowserWindow.getAllWindows().every((other) => other === panel)) panel.destroy()
    }))
  }
  const dispose = () => {
    if (disposed) return
    disposed = true
    clearInterval(timer)
    watcher?.kill()
    app.off("activate", register)
    app.off("browser-window-created", onWindowCreated)
    app.off("will-quit", dispose)
    if (shortcutRegistered) globalShortcut.unregister(shortcut)
    panel?.destroy()
    history.close()
    if (activeService === service) activeService = undefined
  }
  const service = { show, dispose, capture, state, copy }
  activeService = service
  register()
  app.on("activate", register)
  app.on("browser-window-created", onWindowCreated)
  app.once("will-quit", dispose)
  if (options.monitor !== false) {
    if (process.platform === "darwin" && existsSync(helper)) {
      try {
        watcher = spawn(helper, [], { stdio: ["ignore", "pipe", "ignore"] })
      } catch (error) {
        console.warn("剪贴板原生监听未启动，改用轮询", error)
        fallback()
        return service
      }
      let pending = ""
      watcher.stdout?.on("data", (data: Buffer) => {
        pending += data.toString("utf8")
        if (pending.length > 1_000_000) { pending = ""; return }
        const lines = pending.split("\n")
        pending = lines.pop() || ""
        for (const line of lines) { try { const value = JSON.parse(line); capture(Array.isArray(value.files) ? value.files : undefined) } catch { /* Incomplete notification. */ } }
      })
      watcher.on("error", (error) => { if (!disposed) console.warn("剪贴板原生监听未启动", error.message); fallback() })
      watcher.on("exit", (code, signal) => { if (!disposed) console.warn("剪贴板原生监听退出", code, signal); fallback() })
    } else fallback()
  }
  return service
}
